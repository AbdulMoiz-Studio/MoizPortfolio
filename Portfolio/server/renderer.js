/**
 * Website Template Renderer & Synchronizer (renderer.js)
 * Synchronizes HTML pages (index.html, work.html, work/:slug.html, sitemap.xml)
 * with the central database content on every change.
 * Ensures 100% SEO crawlers compatibility with server-rendered content,
 * instant persistence, and zero visual drift.
 */

const fs = require('fs');
const path = require('path');

const ROOT_DIR = path.resolve(__dirname, '..');

function safeWriteFileSync(filePath, content, encoding = 'utf8') {
  try {
    const dir = path.dirname(filePath);
    if (!fs.existsSync(dir)) {
      try { fs.mkdirSync(dir, { recursive: true }); } catch (e) {}
    }
    fs.writeFileSync(filePath, content, encoding);
  } catch (err) {
    if (err.code === 'EROFS' || err.code === 'EACCES' || process.env.VERCEL) {
      console.warn(`[Renderer] Read-only filesystem detected, skipped write to ${path.basename(filePath)}`);
    } else {
      console.error(`[Renderer Write Error] ${filePath}:`, err.message);
    }
  }
}

function escapeHtml(str) {
  if (str === null || str === undefined) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

