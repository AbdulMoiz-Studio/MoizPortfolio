/**
 * Delete a case study page
 */
function deleteCaseStudyPage(slug) {
  const file1 = path.join(ROOT_DIR, 'work', `${slug}.html`);
  const folder = path.join(ROOT_DIR, 'work', slug);

  if (fs.existsSync(file1)) {
    try { fs.unlinkSync(file1); } catch (e) {}
  }
  if (fs.existsSync(folder)) {
    try { fs.rmSync(folder, { recursive: true, force: true }); } catch (e) {}
  }
}

